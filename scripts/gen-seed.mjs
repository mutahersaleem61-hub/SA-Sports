// Generates supabase/seed.sql from src/lib/seed.json so the SQL and the offline fallback never drift apart.
import fs from "node:fs";
const d = JSON.parse(fs.readFileSync("src/lib/seed.json", "utf8"));
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
let sql = "-- Generated by scripts/gen-seed.mjs. Safe to run more than once.\n\n";
sql += "insert into public.categories (slug, name, description, sort_order) values\n";
sql += d.categories.map((c) => `  (${q(c.slug)}, ${q(c.name)}, ${q(c.description)}, ${c.sort_order})`).join(",\n");
sql += "\non conflict (slug) do nothing;\n\n";
sql += "insert into public.products (slug, name, category_slug, price, stock, featured, description, image_url) values\n";
sql += d.products.map((p) => `  (${q(p.slug)}, ${q(p.name)}, ${q(p.category_slug)}, ${p.price}, ${p.stock}, ${p.featured}, ${q(p.description)}, ${q(p.image_url)})`).join(",\n");
sql += "\non conflict (slug) do nothing;\n";
fs.writeFileSync("supabase/seed.sql", sql);
console.log("wrote supabase/seed.sql");
